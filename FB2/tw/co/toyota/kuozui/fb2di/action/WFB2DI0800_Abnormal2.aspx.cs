    protected void Page_Load(object sender, EventArgs e)
    {
        ScriptManager.RegisterClientScriptBlock(gv_result, this.GetType(), "init", "iniForm();", true);
        dept_no = Request.QueryString["dept_no"].ToString();
        dept_name = HttpUtility.UrlDecode(Request.QueryString["dept_name"].ToString());
        target_type = Request.QueryString["target_type"].ToString();
        target_typeName = HttpUtility.UrlDecode(Request.QueryString["target_typeName"].ToString());
        ym = Request.QueryString["ym"].ToString();
        if (!IsPostBack)
        {
            txt_DEPT_NAME.Text = dept_name; //有時會顯示不出來
            txt_TARGET_TYPE.Text = target_typeName;
            txt_YM.Text = ym;
            //取得部門名稱
            getDEPT_NAME();

            getGridView("EMP_ID", 0, 10000);
            getGridView2("EMP_ID", 0, 10000);
            getGridView3("EMP_ID", 0, 10000);
            if (this.gv_result.Rows.Count == 0)
            {
                lb_gv_result.Text = Resources.Resource.wfb2dh_no_data;
            }
            if (this.gv_result2.Rows.Count == 0)
            {
                lb_gv_result2.Text = Resources.Resource.wfb2dh_no_data;
            }
            if (this.gv_result3.Rows.Count == 0)
            {
                lb_gv_result3.Text = Resources.Resource.wfb2dh_no_data;
            }

        }
        //控制Gridview分頁，若有分頁直接copy這段
        if (HID_PageRow.Value != "")
        {
            getGridView(ViewState["SortExpression"].ToString(), 0, Convert.ToInt32(HID_PageRow.Value));
        }
    }

    private void getDEPT_NAME()
    {
        try
        {
            DataTable dt = new DataTable();
            dt = service.getDEPT_NAME(dept_no, "");
            if (dt.Rows.Count > 0)
            {
                txt_DEPT_NAME.Text = dt.Rows[0]["DEPT_NAME"].ToString();
            }
            else
            {
                txt_DEPT_NAME.Text = "";
            }
        }
        catch (Exception ex)
        {
            logger.Error(ex.Message);
            ScriptManager.RegisterClientScriptBlock(this.Page, this.GetType(), "error", "alert('" + ex.Message + "');", true);
        }
    }

    //取得GridView Function
    private void getGridView(string SortExpression, int pageindex, Int32 pagesize)
    {
        try
        {
            //GridView有分頁此段必加 begin
            if (ViewState["PerPageRow"] == null || (ViewState["PerPageRow"] != null && ViewState["PerPageRow"] != HID_PageRow.Value && HID_PageRow.Value != ""))
